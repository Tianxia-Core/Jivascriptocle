// ffp: FFP-JIVA-CODEGEN edge-agent rust
//! Multi-target deterministic code generator for verified `.jiva` AST modules.
//! Emits Rust, Zig, OCaml, TypeScript, and Nix schemas + Stratum-0 gate verifiers.

use crate::transpiler::ast::{ComparisonOp, JivaModule, PrimitiveType, TargetLang};

fn to_snake_case(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 4);
    for (i, ch) in s.chars().enumerate() {
        if ch.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else if ch == '-' {
            out.push('_');
        } else {
            out.push(ch);
        }
    }
    out
}

/// Transpiles a validated `JivaModule` into deterministic source code for `target`.
pub fn transpile_module(module: &JivaModule, target: TargetLang) -> String {
    match target {
        TargetLang::Rust => emit_rust(module),
        TargetLang::Zig => emit_zig(module),
        TargetLang::OCaml => emit_ocaml(module),
        TargetLang::TypeScript => emit_typescript(module),
        TargetLang::Nix => emit_nix(module),
    }
}

fn emit_rust(m: &JivaModule) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "// ffp: {} wire-codec rust\n// Auto-generated by Jivascriptocle v1.2.0 | Domain: {} | AST-BLAKE3: {}\n\nuse serde::{{Deserialize, Serialize}};\n\n",
        m.ffp_id, m.domain, &m.ast_blake3[..16]
    ));
    for k in &m.kennings {
        let const_id = k.key.replace(['-', ':'], "_").to_ascii_uppercase();
        out.push_str(&format!(
            "pub const KENNING_{const_id}: &str = {:?};\n",
            k.expansion
        ));
    }
    if !m.kennings.is_empty() {
        out.push('\n');
    }
    for rec in &m.records {
        let all_copy = rec
            .fields
            .iter()
            .all(|f| !matches!(f.ty, PrimitiveType::Str));
        if all_copy {
            out.push_str(
                "#[repr(C)]\n#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]\n",
            );
        } else {
            out.push_str("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n");
        }
        out.push_str(&format!("pub struct {} {{\n", rec.name));
        for f in &rec.fields {
            let rty = match f.ty {
                PrimitiveType::U64 => "u64",
                PrimitiveType::I64 => "i64",
                PrimitiveType::F64 => "f64",
                PrimitiveType::Bool => "bool",
                PrimitiveType::Bytes32 => "[u8; 32]",
                PrimitiveType::Str => "String",
            };
            out.push_str(&format!("    pub {}: {rty},\n", f.name));
        }
        out.push_str("}\n\n");
    }
    for inv in &m.invariants {
        let fn_name = format!("verify_{}", to_snake_case(&inv.name));
        out.push_str(&format!(
            "pub fn {fn_name}(rec: &{}) -> Result<(), &'static str> {{\n",
            inv.target_record
        ));
        for cl in &inv.clauses {
            let rhs = if cl.field_type == PrimitiveType::F64 && !cl.rhs_literal.contains('.') {
                format!("{}.0", cl.rhs_literal)
            } else {
                cl.rhs_literal.clone()
            };
            out.push_str(&format!(
                "    if !(rec.{} {} {rhs}) {{\n        return Err(\"{}: {} violated\");\n    }}\n",
                cl.field,
                cl.op.as_str(),
                inv.name,
                cl.field
            ));
        }
        out.push_str("    Ok(())\n}\n\n");
    }
    out
}

fn emit_zig(m: &JivaModule) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "// ffp: {} wire-codec zig\n// Auto-generated by Jivascriptocle v1.2.0 | Domain: {} | AST-BLAKE3: {}\n\n",
        m.ffp_id, m.domain, &m.ast_blake3[..16]
    ));
    for rec in &m.records {
        out.push_str(&format!("pub const {} = extern struct {{\n", rec.name));
        for f in &rec.fields {
            let zty = match f.ty {
                PrimitiveType::U64 => "u64",
                PrimitiveType::I64 => "i64",
                PrimitiveType::F64 => "f64",
                PrimitiveType::Bool => "bool",
                PrimitiveType::Bytes32 => "[32]u8",
                PrimitiveType::Str => "[*:0]const u8",
            };
            out.push_str(&format!("    {}: {zty},\n", f.name));
        }
        out.push_str("};\n\n");
    }
    for inv in &m.invariants {
        let fn_name = format!("jiva_verify_{}", to_snake_case(&inv.name));
        out.push_str(&format!(
            "pub export fn {fn_name}(rec: *const {}) bool {{\n",
            inv.target_record
        ));
        let exprs: Vec<String> = inv
            .clauses
            .iter()
            .map(|c| format!("(rec.{} {} {})", c.field, c.op.as_str(), c.rhs_literal))
            .collect();
        out.push_str(&format!("    return {};\n}}\n\n", exprs.join(" and ")));
    }
    out
}

fn emit_ocaml(m: &JivaModule) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "(* ffp: {} capability-proxy ocaml *)\n(* Auto-generated by Jivascriptocle v1.2.0 | Domain: {} | AST-BLAKE3: {} *)\n\n",
        m.ffp_id, m.domain, &m.ast_blake3[..16]
    ));
    for rec in &m.records {
        let rname = to_snake_case(&rec.name);
        out.push_str(&format!("type {rname} = {{\n"));
        for f in &rec.fields {
            let oty = match f.ty {
                PrimitiveType::U64 | PrimitiveType::I64 => "int",
                PrimitiveType::F64 => "float",
                PrimitiveType::Bool => "bool",
                PrimitiveType::Bytes32 | PrimitiveType::Str => "string",
            };
            out.push_str(&format!("  {}: {oty};\n", f.name));
        }
        out.push_str("}\n\n");
    }
    for inv in &m.invariants {
        let fn_name = format!("verify_{}", to_snake_case(&inv.name));
        let rtype = to_snake_case(&inv.target_record);
        out.push_str(&format!("let {fn_name} (rec_val : {rtype}) : bool =\n"));
        let exprs: Vec<String> = inv
            .clauses
            .iter()
            .map(|c| {
                let op = match c.op {
                    ComparisonOp::Eq => "=",
                    ComparisonOp::Ne => "<>",
                    other => other.as_str(),
                };
                let rhs = if c.field_type == PrimitiveType::F64 && !c.rhs_literal.contains('.') {
                    format!("{}.0", c.rhs_literal)
                } else {
                    c.rhs_literal.clone()
                };
                format!("(rec_val.{} {op} {rhs})", c.field)
            })
            .collect();
        out.push_str(&format!("  {}\n\n", exprs.join(" &&\n  ")));
    }
    out
}

fn emit_typescript(m: &JivaModule) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "// ffp: {} frontend typescript\n// Auto-generated by Jivascriptocle v1.2.0 | Domain: {} | AST-BLAKE3: {}\n\n",
        m.ffp_id, m.domain, &m.ast_blake3[..16]
    ));
    for rec in &m.records {
        out.push_str(&format!("export interface {} {{\n", rec.name));
        for f in &rec.fields {
            let tsty = match f.ty {
                PrimitiveType::U64 | PrimitiveType::I64 | PrimitiveType::F64 => "number",
                PrimitiveType::Bool => "boolean",
                PrimitiveType::Bytes32 | PrimitiveType::Str => "string",
            };
            out.push_str(&format!("  readonly {}: {tsty};\n", f.name));
        }
        out.push_str("}\n\n");
    }
    for inv in &m.invariants {
        out.push_str(&format!(
            "export function verify{}(rec: {}): boolean {{\n",
            inv.name, inv.target_record
        ));
        let exprs: Vec<String> = inv
            .clauses
            .iter()
            .map(|c| {
                let op = match c.op {
                    ComparisonOp::Eq => "===",
                    ComparisonOp::Ne => "!==",
                    other => other.as_str(),
                };
                format!("(rec.{} {op} {})", c.field, c.rhs_literal)
            })
            .collect();
        out.push_str(&format!("  return {};\n}}\n\n", exprs.join(" && ")));
    }
    out
}

fn emit_nix(m: &JivaModule) -> String {
    let mut out = String::new();
    let mod_key = to_snake_case(&m.name).replace('_', "-");
    out.push_str(&format!(
        "# ffp: {} declarative nix\n# Auto-generated by Jivascriptocle v1.2.0 | Domain: {} | AST-BLAKE3: {}\n{{ lib, ... }}:\n{{\n  options.tianxia.jiva.{mod_key} = {{\n",
        m.ffp_id, m.domain, &m.ast_blake3[..16]
    ));
    for rec in &m.records {
        let rkey = to_snake_case(&rec.name).replace('_', "-");
        out.push_str(&format!("    {rkey} = {{\n"));
        for f in &rec.fields {
            let nty = match f.ty {
                PrimitiveType::U64 => "lib.types.ints.unsigned",
                PrimitiveType::I64 => "lib.types.int",
                PrimitiveType::F64 => "lib.types.float",
                PrimitiveType::Bool => "lib.types.bool",
                PrimitiveType::Bytes32 | PrimitiveType::Str => "lib.types.str",
            };
            out.push_str(&format!(
                "      {} = lib.mkOption {{ type = {nty}; description = \"{} field {}\"; }};\n",
                f.name, rec.name, f.name
            ));
        }
        out.push_str("    };\n");
    }
    out.push_str("  };\n}\n");
    out
}
